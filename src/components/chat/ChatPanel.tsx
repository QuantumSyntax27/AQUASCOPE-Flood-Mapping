import { useState } from 'react';

type Message = {
  id: string;
  text: string;
  isUser: boolean;
};

const suggestedQuestions: string[] = [
  'What is AQUASCOPE?',
  'How do I use this website?',
  'What is AOI?',
  'How does flood analysis work?',
  'What does FALLBACK mean?',
  'What are the limitations of this project?',
];

const fallbackResponses: Record<string, string> = {
  'what is aquascope': 'AQUASCOPE is a satellite-powered flood impact mapping and disaster intelligence platform. It uses Sentinel-1 satellite imagery to map flood extents, assess infrastructure impact, and analyze road connectivity in flood-affected areas. The platform runs in demo mode with simulated data for interface validation.',
  'how do i use this website': 'To use AQUASCOPE: 1) Navigate to the Home page. 2) Enter a location (e.g., "Trishuli, Nepal") or draw an Area of Interest (AOI). 3) Select a flood event date (YYYY-MM-DD). 4) Click "Run Analysis" to process the data through our pipeline. 5) View results across the Dashboard, Flood Map, Infrastructure Impact, Connectivity, and Validation pages.',
  'what is aoi': 'AOI stands for Area of Interest. It\'s a polygonal region you define on the map or specify by coordinates that bounds the area where AQUASCOPE will analyze flood impact. The backend can also derive a default corridor around a location name if you omit the AOI.',
  'how does flood analysis work': 'Flood analysis in AQUASCOPE follows a 6-stage pipeline: 1) Satellite scene discovery (Sentinel-1 pre-event/co-event/post-event), 2) Preprocessing (radiometric calibration, terrain correction, alignment), 3) AI flood mapping (change detection on preprocessed data), 4) Infrastructure impact (intersection with OSM roads/buildings/bridges), 5) Connectivity analysis (road network graph, disconnection assessment), 6) Validation (comparison against reference mapping). The current implementation uses deterministic mock services for all stages.',
  'what does fallback mean': 'FALLBACK means the result was generated by the deterministic mock service because the real API (Copernicus Data Space, OSM, etc.) was unavailable. All AQUASCOPE services have dual implementation — they try the real service first, then fall back to mock data. Results include a "source" field marked "REAL" or "FALLBACK" so you can distinguish the data provenance.',
  'what are the limitations': 'Key limitations: 1) All mock results are DEMO/SIMULATED DATA with no real satellite observations. 2) Flood overlap does not imply destruction — "potentially affected" ≠ "destroyed". 3) Terrain uncertainty (SAR layover/shadow) reduces reliability in mountainous areas. 4) AOI area calculations use bounding-box approximation, not precise geospatial analysis. 5) Validation metrics are zero when no real reference data is available. 6) Results are preliminary and should be verified with local field information.',
};

const initialMessages: Message[] = [
  {
    id: '1',
    text: 'Hello! I\'m AQUASCOPE\'s AI assistant. I can answer questions about this satellite flood-mapping platform. How can I help you today?',
    isUser: false,
  },
];

export function ChatPanel() {
  const [messages, setMessages] = useState<Message[]>(initialMessages);
  const [input, setInput] = useState('');
  const [loading, setLoading] = useState(false);

  const sendMessage = async (text: string) => {
    if (!text.trim() || loading) return;

    const newMessage: Message = {
      id: Date.now().toString(),
      text,
      isUser: true,
    };

    setMessages([...messages, newMessage]);
    setInput('');
    setLoading(true);

    // Simulate processing time
    await new Promise((resolve) => setTimeout(resolve, 500));

    const response = getResponse(text);
    setMessages([...messages, { id: Date.now().toString() + 'a', text: response, isUser: false }]);
    setLoading(false);
  };

  const getResponse = (text: string): string => {
    const lowered = text.toLowerCase().trim();

    // Check for exact/semimatching suggested questions first
    for (const q of suggestedQuestions) {
      if (lowered.includes(q.toLowerCase())) {
        const response = fallbackResponses[q.toLowerCase()] || fallbackResponses['what is aquascope'] || 'I have information about that in the knowledge base!';
        return response;
      }
    }

    // Keyword-based matching
    for (const [keyword, response] of Object.entries(fallbackResponses)) {
      if (lowered.includes(keyword)) {
        return response;
      }
    }

    // Default honest response
    return "I don't have enough information about that in the current AQUASCOPE knowledge base. Would you like to ask about flood analysis, the demo mode, or the project's limitations?";
  };

  return (
    <div className="fixed bottom-4 left-1/2 -translate-x-1/2 w-full max-w-sm z-50">
      <div className="bg-navy-950 border border-navy-800 rounded-2xl overflow-hidden shadow-xl max-h-80">
        <div className="h-16 border-b border-navy-800 flex items-center justify-start px-4 text-sm font-medium text-navy-300">
          AQUASCOPE AI Assistant
        </div>
        <div className="flex flex-col h-full overflow-y-auto px-4 py-3 space-y-2">
          {messages.map((msg) => (
            <div
              key={msg.id}
              className={classNames(
                'max-w-xs p-3 rounded-lg',
                msg.isUser ? 'bg-brand-600 text-white items-end' : 'bg-navy-800 text-white items-start',
                'self-' + (msg.isUser ? 'end' : 'start')
              )}
            >
              <p className="whitespace-pre-wrap text-[12px] leading-relaxed">{msg.text}</p>
            </div>
          ))}

          {loading && (
            <div className="max-w-xs p-3 rounded-lg bg-navy-800 text-white items-end">
              <p className="text-xs italic">Assistant is thinking...</p>
            </div>
          )}

          {/* Suggested questions below messages */}
          <div className="flex flex-wrap gap-2 pt-2">
            {suggestedQuestions.map((question) => (
              <button
                key={question}
                className={classNames(
                  'px-3 py-1.5 text-xs text-navy-300 hover:bg-navy-700/50 rounded-full border border-navy-700/50 cursor-pointer',
                  'flex items-center gap-1'
                )}
                onClick={() => sendMessage(question)}
                aria-label={`Ask: ${question}`}
                title={question}
              >
                <span>{question}</span>
              </button>
            ))}
          </div>
        </div>

        {/* Input area */}
        <div className="p-3 border-t border-navy-800 flex gap-2">
          <input
            value={input}
            onChange={(e) => setInput(e.target.value)}
            onKeyDown={(e) => e.key === 'Enter' && sendMessage(input)}
            placeholder="Type a question..."
            className="flex-1 border rounded-lg p-2 text-sm text-white focus:bg-navy-800 focus:outline-none"
            aria-label="Message input"
          />
          <button
            onClick={() => sendMessage(input)}
            className="bg-indigo-600 text-white px-4 rounded-lg text-sm hover:bg-indigo-500"
            disabled={!input.trim()}
            aria-label="Send message"
          >
            Send
          </button>
        </div>
      </div>
    </div>
  );
}